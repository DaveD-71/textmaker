class StepProfiler:
    """Progress logger with optional timing summary for conversion stages."""

    def __init__(
        self,
        enabled: bool = False,
        *,
        progress: bool = True,
        warn_after_seconds: float = 30.0,
    ):
        self.enabled = enabled
        self.progress = progress
        self.warn_after_seconds = max(0.0, warn_after_seconds)
        self.records: list[tuple[str, float]] = []

    @contextmanager
    def step(self, name: str):
        if self.progress:
            print(f'[progress] {name}: started', flush=True)
        start = time.perf_counter()
        stop_event = threading.Event()
        watchdog = self._start_watchdog(name, start, stop_event)
        try:
            yield
        except Exception:
            elapsed = time.perf_counter() - start
            if self.progress:
                print(f'[error] {name}: failed after {elapsed:.3f}s', flush=True)
            raise
        finally:
            stop_event.set()
            if watchdog is not None:
                watchdog.join(timeout=0.2)
            elapsed = time.perf_counter() - start
            if self.progress:
                print(f'[progress] {name}: done in {elapsed:.3f}s', flush=True)
            if self.enabled:
                self.records.append((name, elapsed))
                print(f'[profile] {name}: {elapsed:.3f}s')

    def _start_watchdog(self, name: str, start: float, stop_event: threading.Event):
        if not self.progress or self.warn_after_seconds <= 0:
            return None

        def watch() -> None:
            while not stop_event.wait(self.warn_after_seconds):
                elapsed = time.perf_counter() - start
                print(
                    f'[warn] {name}: still running after {elapsed:.1f}s',
                    flush=True,
                )

        thread = threading.Thread(target=watch, daemon=True)
        thread.start()
        return thread

    def summary(self) -> None:
        if not self.enabled or not self.records:
            return
        total = sum(elapsed for _, elapsed in self.records)
        print('[profile] markdown-to-docx summary:')
        for name, elapsed in self.records:
            print(f'[profile]   {name}: {elapsed:.3f}s')
        print(f'[profile]   total measured: {total:.3f}s')


def check_pandoc() -> None:
    if shutil.which('pandoc') is None:
        print('Error: pandoc binary not found on PATH. Install from https://pandoc.org/installing.html')
        sys.exit(2)


def get_caller_cwd() -> Path:
    raw_cwd = os.environ.get('TEXTMAKER_CALLER_CWD')
    if raw_cwd:
        return Path(raw_cwd)
    return Path.cwd()


def is_windows_fallback_cwd(path: Path) -> bool:
    windows_dir = Path(os.environ.get('WINDIR', r'C:\Windows')).resolve()
    try:
        resolved = path.resolve()
    except OSError:
        return False
    return resolved == windows_dir or resolved == windows_dir / 'System32'


def resolve_user_path(raw_path: str, *, base_dir: Path) -> Path:
    path = Path(raw_path)
    if path.is_absolute():
        return path.resolve(strict=False)
    return (base_dir / path).resolve(strict=False)


def path_suffix_parts(raw_path: str) -> tuple[str, ...]:
    parts = []
    for part in Path(raw_path).parts:
        if part in ('.', ''):
            continue
        parts.append(part.lower())
    return tuple(parts)


def match_path_suffix(candidate: Path, suffix_parts: tuple[str, ...]) -> bool:
    candidate_parts = tuple(part.lower() for part in candidate.parts)
    if len(candidate_parts) < len(suffix_parts):
        return False
    return candidate_parts[-len(suffix_parts):] == suffix_parts


def infer_base_dir(raw_path: str, matched_path: Path) -> Path | None:
    suffix_parts = path_suffix_parts(raw_path)
    if not suffix_parts:
        return matched_path.parent
    parent = matched_path
    for _ in suffix_parts:
        parent = parent.parent
    return parent


def iter_candidate_base_dirs() -> Iterable[Path]:
    roots = [WORKSPACE_ROOT.parent, WORKSPACE_ROOT]
    seen: set[str] = set()
    for root in roots:
        root_key = str(root).lower()
        if root_key in seen or not root.exists():
            continue
        seen.add(root_key)
        yield root

        try:
            children = [child for child in root.iterdir() if child.is_dir()]
        except OSError:
            continue

        for child in children:
            child_key = str(child).lower()
            if child_key not in seen:
                seen.add(child_key)
                yield child

            try:
                grandchildren = [grandchild for grandchild in child.iterdir() if grandchild.is_dir()]
            except OSError:
                continue

            for grandchild in grandchildren:
                grandchild_key = str(grandchild).lower()
                if grandchild_key in seen:
                    continue
                seen.add(grandchild_key)
                yield grandchild


def search_for_existing_path(raw_path: str) -> tuple[Path | None, Path | None]:
    relative_path = Path(raw_path)
    if not relative_path.name:
        return None, None

    matches: list[Path] = []
    for base_dir in iter_candidate_base_dirs():
        candidate = base_dir / relative_path
        if candidate.exists():
            matches.append(candidate)
    if len(matches) == 1:
        match = matches[0].resolve(strict=False)
        return match, infer_base_dir(raw_path, match)
    return None, None


def resolve_existing_path(raw_path: str, *, base_dir: Path) -> tuple[Path, Path | None]:
    path = Path(raw_path)
    if path.is_absolute():
        normalized = path.resolve(strict=False)
        return normalized, normalized.parent

    direct = base_dir / path
    if direct.exists():
        normalized = direct.resolve(strict=False)
        return normalized, base_dir.resolve(strict=False)

    cwd_path = Path.cwd() / path
    if cwd_path.exists():
        normalized = cwd_path.resolve(strict=False)
        return normalized, Path.cwd().resolve(strict=False)

    searched, inferred_base = search_for_existing_path(raw_path)
    if searched is not None:
        return searched, inferred_base

    return direct, None


def build_pandoc_cmd(
    input_path: Path,
    output_path: Path,
    reference: Path,
    toc: bool,
    toc_depth: int,
    lua_filters: Iterable[Path] = (),
    use_pagebreak_filter: bool = True,
) -> List[str]:
    pandoc_input_fmt = 'markdown+fancy_lists'

    cmd = [
        'pandoc',
        str(input_path),
        '--from', pandoc_input_fmt,
        '--to', 'docx',
        '--output', str(output_path),
    ]
    pagebreak_filter = Path(__file__).parent / 'pagebreak.lua'
    if use_pagebreak_filter and pagebreak_filter.exists():
        cmd += ['--lua-filter', str(pagebreak_filter)]
    for lua_filter in lua_filters:
        cmd += ['--lua-filter', str(lua_filter)]
    if reference and reference.exists():
        cmd += ['--reference-doc', str(reference)]
    if toc:
        cmd += ['--toc', f'--toc-depth={toc_depth}']
    return cmd


_HTML_ONLY_LINE_RE = re.compile(r'^\s*(?:<[^>]+>\s*)+$')
_HORIZONTAL_RULE_RE = re.compile(r'^\s{0,3}(?:-{3,}|\*{3,}|_{3,})\s*$')
_BULLET_LIST_RE = re.compile(r'^\s*[-+*]\s+')
_ORDERED_LIST_RE = re.compile(r'^\s*\d+[.)]\s+')
_HEADING_RE = re.compile(r'^\s*(#{1,6})\s+(.+?)\s*$')


